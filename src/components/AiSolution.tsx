import { useState } from 'react';
import { renderMarkdown } from '../lib/markdown';
import type { AiApproach, AiSolutionData } from '../types';

const CODE_LANGS: { id: keyof AiApproach['c']; label: string }[] = [
  { id: 'python', label: 'Python3' },
  { id: 'cpp', label: 'C++' },
  { id: 'java', label: 'Java' },
  { id: 'javascript', label: 'JavaScript' },
  { id: 'typescript', label: 'TypeScript' },
  { id: 'go', label: 'Go' },
];

export default function AiSolution({ data }: { data: AiSolutionData }) {
  return (
    <div className="desc-body ai-body">
      <div className="ai-head">
        <span className="ai-badge" title={`Generated by ${data.m}`}>
          ✦ AI Explains
        </span>
        <span className="ai-model muted">{data.m}</span>
      </div>

      {data.fig && (
        <img className="ai-fig" src={data.fig} alt="Approach illustration" loading="lazy" />
      )}

      {data.k.length > 0 && (
        <div className="ai-cards">
          {data.k.map((insight, i) => (
            <div key={i} className="ai-card">
              <div className="ai-card-label">Key insight {data.k.length > 1 ? i + 1 : ''}</div>
              <div dangerouslySetInnerHTML={{ __html: renderMarkdown(insight) }} />
            </div>
          ))}
        </div>
      )}

      <h3 className="ai-section-title">Understanding the problem</h3>
      <div dangerouslySetInnerHTML={{ __html: renderMarkdown(data.o) }} />

      {data.a.map((ap, i) => (
        <Approach key={i} ap={ap} idx={i} total={data.a.length} />
      ))}

      {data.w && (
        <>
          <h3 className="ai-section-title">Wrap-up &amp; follow-ups</h3>
          <div dangerouslySetInnerHTML={{ __html: renderMarkdown(data.w) }} />
        </>
      )}
    </div>
  );
}

function Approach({ ap, idx, total }: { ap: AiApproach; idx: number; total: number }) {
  const langs = CODE_LANGS.filter((l) => ap.c[l.id]);
  const [lang, setLang] = useState<string>(langs[0]?.id ?? 'python');
  const [copied, setCopied] = useState(false);
  const code = ap.c[lang as keyof AiApproach['c']] ?? '';

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1200);
    } catch {
      /* clipboard unavailable */
    }
  };

  return (
    <div className="ai-approach">
      <div className="ai-approach-head">
        <span className="ai-approach-num">{idx + 1}</span>
        <h4>{ap.n}</h4>
        {idx === total - 1 && total > 1 && <span className="ai-optimal">optimal</span>}
      </div>

      {ap.i && <div dangerouslySetInnerHTML={{ __html: renderMarkdown(ap.i) }} />}

      {ap.s.length > 0 && (
        <ol className="ai-steps">
          {ap.s.map((st, i) => (
            <li key={i} dangerouslySetInnerHTML={{ __html: renderMarkdown(st) }} />
          ))}
        </ol>
      )}

      {(ap.t || ap.sp) && (
        <div className="ai-complexity">
          {ap.t && (
            <span className="cx-pill" title="Time complexity">
              ⏱ {ap.t}
            </span>
          )}
          {ap.sp && (
            <span className="cx-pill" title="Space complexity">
              ▦ {ap.sp}
            </span>
          )}
        </div>
      )}

      {langs.length > 0 && (
        <div className="ai-code-wrap">
          <div className="ai-code-tabs">
            {langs.map((l) => (
              <button
                key={l.id}
                className={`ai-code-tab${lang === l.id ? ' on' : ''}`}
                onClick={() => setLang(l.id)}
              >
                {l.label}
              </button>
            ))}
            <button className="ai-copy-btn" onClick={copy}>
              {copied ? 'Copied!' : 'Copy'}
            </button>
          </div>
          <pre className="ai-code">
            <code>{code}</code>
          </pre>
        </div>
      )}
    </div>
  );
}
